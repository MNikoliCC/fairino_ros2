#!/usr/bin/env python3

"""Generate the convex-hull collision model used by the servo self-collision barrier.

Why: the FAIRINO collision meshes have 5k-22k triangles per link. Exact mesh
distances for the 5 self-collision pairs that remain after the SRDF take
7-19 ms, far above the 1 ms servo budget. The convex hull of each link mesh
(trimesh/qhull, 750-1300 triangles) encloses the mesh, so the hull distance is
never larger than the true distance (conservative). The servo converts these
hull meshes into coal::Convex objects (GJK), which brings the evaluation of all
pairs to tens of microseconds.

The kinematics of the generated URDF are identical to fairino20_v6.urdf; only
<collision> mesh filenames point to the hull meshes. Visual meshes are kept.

Validation on random joint configurations:
  - conservativeness: hull/convex distance <= mesh distance for every pair;
  - tightness: how much closer the hull reports than the mesh;
  - timing of the convex-object distance evaluation.

Usage (inside the ROS container, then copy the outputs into the source tree):
  python3 generate_servo_collision_model.py --mesh-dir /tmp/servo_collision \
      --urdf /tmp/fairino20_v6_servo_collision.urdf
"""

from __future__ import annotations

import argparse
import os
import re
import time

import numpy as np
import pinocchio as pin
import trimesh
from ament_index_python.packages import get_package_share_path

PACKAGE_URI = "package://fairinoplan_bringup/meshes/servo_collision"


def setup(urdf_xml: str, srdf_xml: str, package_dirs: list[str], convex: bool):
    model = pin.buildModelFromXML(urdf_xml)
    geom = pin.buildGeomFromUrdfString(model, urdf_xml, pin.GeometryType.COLLISION, package_dirs=package_dirs)
    if convex:
        for obj in geom.geometryObjects:
            obj.geometry.buildConvexRepresentation(False)
            obj.geometry = obj.geometry.convex
    geom.addAllCollisionPairs()
    pin.removeCollisionPairsFromXML(model, geom, srdf_xml)
    return model, geom, model.createData(), pin.GeometryData(geom)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--mesh-dir", required=True)
    parser.add_argument("--urdf", required=True)
    parser.add_argument("--validate", type=int, default=500)
    args = parser.parse_args()

    description = get_package_share_path("fairino_description")
    bringup = get_package_share_path("fairinoplan_bringup")
    urdf_xml = (description / "urdf" / "fairino20_v6.urdf").read_text()
    srdf_xml = (bringup / "config" / "fairino20_v6_robot.srdf").read_text()
    os.makedirs(args.mesh_dir, exist_ok=True)

    def collision_block(match: re.Match) -> str:
        block = match.group(0)
        mesh_uri = re.search(r'filename="([^"]+)"', block).group(1)
        path = mesh_uri.replace("package://fairino_description", description.as_posix())
        name = os.path.basename(path)
        mesh = trimesh.load(path, force="mesh")
        hull = mesh.convex_hull
        hull.export(os.path.join(args.mesh_dir, name))
        print(f"{name:20s} {len(mesh.faces):6d} triangles -> hull {len(hull.faces):5d} triangles")
        return block.replace(mesh_uri, f"{PACKAGE_URI}/{name}")

    hull_urdf = re.sub(r"<collision>.*?</collision>", collision_block, urdf_xml, flags=re.S)
    header = (
        "<!-- GENERATED by fairino_cartesian_servo/tools/generate_servo_collision_model.py.\n"
        "     Identical to fairino_description/urdf/fairino20_v6.urdf except that every <collision>\n"
        "     mesh is replaced by its convex hull (conservative, used only by the servo\n"
        "     self-collision barrier). Do not edit by hand. -->\n"
    )
    hull_urdf = re.sub(r"(<\?xml[^>]*\?>\s*)", r"\1" + header, hull_urdf, count=1)
    with open(args.urdf, "w", encoding="utf-8") as handle:
        handle.write(hull_urdf)

    # Validation against the original meshes. The hull URDF references
    # package://fairinoplan_bringup; resolve it to the freshly written meshes.
    resolved = hull_urdf.replace(PACKAGE_URI, "file://" + os.path.abspath(args.mesh_dir))
    package_dirs = [description.as_posix(), description.parent.as_posix()]
    mesh_model = setup(urdf_xml, srdf_xml, package_dirs, convex=False)
    convex_model = setup(resolved, srdf_xml, package_dirs, convex=True)
    rng = np.random.default_rng(7)
    gaps: dict[str, list[float]] = {}
    timings = []
    violations = 0
    for _ in range(args.validate):
        q = rng.uniform(mesh_model[0].lowerPositionLimit, mesh_model[0].upperPositionLimit)
        pin.computeDistances(mesh_model[0], mesh_model[2], mesh_model[1], mesh_model[3], q)
        started = time.perf_counter()
        pin.computeDistances(convex_model[0], convex_model[2], convex_model[1], convex_model[3], q)
        timings.append((time.perf_counter() - started) * 1000.0)
        for index, pair in enumerate(mesh_model[1].collisionPairs):
            key = (
                f"{mesh_model[1].geometryObjects[pair.first].name} - "
                f"{mesh_model[1].geometryObjects[pair.second].name}"
            )
            gap = mesh_model[3].distanceResults[index].min_distance - convex_model[3].distanceResults[index].min_distance
            if gap < -1e-4:
                violations += 1
            gaps.setdefault(key, []).append(gap)
    print(f"\nvalidated {args.validate} random configurations, {len(mesh_model[1].collisionPairs)} pairs")
    print(f"non-conservative evaluations (convex farther than mesh by > 0.1 mm): {violations}")
    for key, values in gaps.items():
        values = np.asarray(values) * 1000.0
        print(f"  {key:34s} convex closer by mean {values.mean():5.1f} mm, max {values.max():5.1f} mm")
    print(
        f"convex distance evaluation, all pairs (Python): mean {np.mean(timings):.3f} ms, "
        f"p99 {np.percentile(timings, 99):.3f} ms, max {np.max(timings):.3f} ms"
    )
    if violations:
        raise SystemExit("hull model is not conservative")


if __name__ == "__main__":
    main()
